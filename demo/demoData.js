export const YEARS = ["2021", "2022", "2023", "2024", "2025"];

/** ピーク月を中心に山なりの重みを作る（乱数を使わず決定的）。 */
function seasonalWeights(peakMonth) {
  const w = Array.from({ length: 12 }, (_, i) => {
    let d = Math.abs(i + 1 - peakMonth);
    d = Math.min(d, 12 - d); // 12月と1月は隣同士
    return Math.exp(-(d * d) / 1.9);
  });
  const sum = w.reduce((a, b) => a + b, 0);
  return w.map((x) => x / sum);
}

/** 品種名から決定的に成長パターンを決める。 */
function trendOf(name) {
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.codePointAt(0)) % 997;
  return h % 4; // 0=横ばい 1=成長 2=減少 3=山なり
}

function yearFactor(trend, i, n) {
  const t = i / (n - 1);
  switch (trend) {
    case 1: return 0.45 + 0.9 * t;                    // 成長
    case 2: return 1.25 - 0.8 * t;                    // 減少
    case 3: return 0.6 + 0.8 * Math.sin(Math.PI * t); // 山なり
    default: return 0.85 + 0.1 * Math.sin(t * 6.28);  // 横ばい
  }
}

/**
 * 「年月・産地・タイプ・品種・売上」のフラットな行データ。
 * 事前集計は不要 — 同じ組み合わせの行が何行あっても勝手に合算される。
 */
export const DEMO_ROWS = Object.entries(CATALOG).flatMap(([type, list]) =>
  list.flatMap(([variety, base, peak, region]) => {
    const weights = seasonalWeights(peak);
    const trend = trendOf(variety);
    return YEARS.flatMap((year, yi) => {
      const yearTotal = base * 1000 * yearFactor(trend, yi, YEARS.length);
      return weights
        .map((w, mi) => ({
          ym: `${year}-${String(mi + 1).padStart(2, "0")}`,
          region,
          type,
          variety,
          sales: Math.round(yearTotal * w),
        }))
        .filter((row) => row.sales > 0); // 売上ゼロの月は行として存在しない想定
    });
  })
);

